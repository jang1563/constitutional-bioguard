#!/usr/bin/env python3
"""Export trained model and dataset to HuggingFace Hub.

Usage:
    python scripts/experiments/export_to_hf.py --model
    python scripts/experiments/export_to_hf.py --model \
        --model-repo jang1563/constitutional-bioguard-v4 \
        --card-file docs/MODEL_CARD_V4.md
    python scripts/experiments/export_to_hf.py --dataset --dataset-repo jang1563/constitutional-bioguard-dataset
"""

from __future__ import annotations

import argparse
import json
import logging
import shutil
import sys
from pathlib import Path
from typing import Optional

PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from constitutional_bioguard.config import (  # noqa: E402
    CONSTITUTION_FILE,
    DATA_PROCESSED,
    METRICS_DIR,
    MODELS_DIR,
)

logger = logging.getLogger(__name__)


def export_model(
    model_dir: Path,
    repo_id: str,
    private: bool = False,
    regenerate_card: bool = False,
    card_file: Optional[Path] = None,
) -> str:
    """Push trained model to HuggingFace Hub.

    Args:
        model_dir: Path to the trained model directory.
        repo_id: HuggingFace repo ID (e.g., "jang1563/bioguard-deberta-v1").
        private: Whether to create a private repo.
        regenerate_card: Overwrite an existing model card with the generated fallback card.
        card_file: Optional hand-maintained model card to copy into model_dir/README.md.

    Returns:
        URL of the uploaded model.
    """
    from huggingface_hub import HfApi

    api = HfApi()

    # Create model card
    metrics_file = METRICS_DIR / "internal_evaluation.json"
    metrics = {}
    if metrics_file.exists():
        with open(metrics_file, encoding="utf-8") as f:
            metrics = json.load(f)

    internal = metrics.get("internal_metrics", {})
    model_name = repo_id.split("/")[-1]
    model_card = f"""---
library_name: transformers
tags:
  - safety
  - biosecurity
  - content-classification
  - constitutional-classifiers
  - deberta-v3
datasets:
  - custom
metrics:
  - f1
  - auroc
  - precision
  - recall
model-index:
  - name: {model_name}
    results:
      - task:
          type: text-classification
          name: Biological Dual-Use Content Classification
        metrics:
          - name: F1
            type: f1
            value: {internal.get('f1', 'N/A')}
          - name: AUROC
            type: auroc
            value: {internal.get('auroc', 'N/A')}
          - name: Precision
            type: precision
            value: {internal.get('precision', 'N/A')}
          - name: Recall
            type: recall
            value: {internal.get('recall', 'N/A')}
---

# {model_name}

Binary classifier for detecting biological dual-use content, built using
Anthropic's Constitutional Classifiers methodology. This fallback card is
generated by `scripts/experiments/export_to_hf.py`; for public releases, prefer a
hand-maintained `--card-file`.

## Model Description

- **Base model**: microsoft/deberta-v3-base
- **Task**: Binary classification (SAFE / UNSAFE)
- **Input format**: `[CLS] query [SEP] response [SEP]`
- **Training data**: ~4,500 synthetic examples generated from a 56-rule biosafety constitution

## Performance

| Metric | Value |
|--------|-------|
| F1 | {internal.get('f1', 'N/A')} |
| AUROC | {internal.get('auroc', 'N/A')} |
| Precision | {internal.get('precision', 'N/A')} |
| Recall | {internal.get('recall', 'N/A')} |
| Over-refusal FPR | See repository release notes |
| Adversarial robustness | See repository release notes |

## NSABB Categories

Covers all 7 National Science Advisory Board for Biosecurity categories:
enhance_harm, disrupt_immunity, confer_resistance, increase_stability,
alter_host_range, enhance_susceptibility, generate_reconstruct.

## Usage

```python
from transformers import AutoTokenizer, AutoModelForSequenceClassification
import torch

tokenizer = AutoTokenizer.from_pretrained("{repo_id}")
model = AutoModelForSequenceClassification.from_pretrained("{repo_id}")

query = "How does CRISPR work?"
response = "CRISPR uses guide RNA..."
inputs = tokenizer(query, response, return_tensors="pt", truncation=True, max_length=512)
with torch.no_grad():
    logits = model(**inputs).logits
    probs = torch.softmax(logits, dim=-1)
    label = "UNSAFE" if probs[0, 1] > 0.5 else "SAFE"
    print(f"{{label}} (confidence: {{probs[0, 1]:.3f}})")
```

## License

MIT
"""

    # Write model card. A hand-maintained card (richer than this generated
    # template) may already exist; preserve it rather than overwriting.
    # Use --card-file for release-grade cards, or --regenerate-card to force
    # the generated fallback template.
    card_path = model_dir / "README.md"
    if card_file is not None:
        if not card_file.exists():
            raise FileNotFoundError(f"model card not found: {card_file}")
        shutil.copy2(card_file, card_path)
        print(f"Copied model card from {card_file} to {card_path}.")
    elif card_path.exists() and not regenerate_card:
        print(f"Existing model card found at {card_path} — keeping it. "
              f"Pass --regenerate-card to overwrite with the generated template.")
    else:
        with open(card_path, "w", encoding="utf-8") as f:
            f.write(model_card)

    # Create repo if needed, then upload
    api.create_repo(repo_id=repo_id, repo_type="model", exist_ok=True, private=private)
    ignore_patterns = ["checkpoint-*", ".model.safetensors.*", "*.tmp"]
    if hasattr(api, "upload_large_folder"):
        api.upload_large_folder(
            folder_path=str(model_dir),
            repo_id=repo_id,
            repo_type="model",
            private=private,
            ignore_patterns=ignore_patterns,
            num_workers=1,
            print_report=True,
            print_report_every=60,
        )
    else:
        api.upload_folder(
            folder_path=str(model_dir),
            repo_id=repo_id,
            repo_type="model",
            create_pr=False,
            ignore_patterns=ignore_patterns,
        )

    logger.info("Model uploaded to: https://huggingface.co/%s", repo_id)
    return f"https://huggingface.co/{repo_id}"


def export_dataset(
    repo_id: str,
    private: bool = False,
) -> str:
    """Push dataset and constitution to HuggingFace Hub.

    Args:
        repo_id: HuggingFace repo ID (e.g., "jang1563/bioguard-dataset").
        private: Whether to create a private repo.

    Returns:
        URL of the uploaded dataset.
    """
    from huggingface_hub import HfApi

    api = HfApi()

    # Create dataset card
    dataset_card = """---
task_categories:
  - text-classification
tags:
  - safety
  - biosecurity
  - constitutional-classifiers
  - synthetic-data
language:
  - en
  - es
  - fr
  - zh
  - ar
  - ru
size_categories:
  - 1K<n<10K
---

# BioGuard Dataset

Synthetic training data for biological dual-use content classification,
generated using Anthropic's Constitutional Classifiers methodology.

## Dataset Description

- **Source**: Generated via Claude API from a 56-rule biosafety constitution
- **Size**: ~4,500 examples (3,062 train / 697 val / 643 test)
- **Labels**: Binary (SAFE=0 / UNSAFE=1)
- **Format**: JSONL with fields: text, label, fine_label, category

## Constitution

The biosafety constitution (included as `biosafety_constitution.yaml`) defines
56 rules across all 7 NSABB dual-use research categories.

## Data Sources

- **Permitted examples**: Safe biological research queries and responses
- **Restricted examples**: Queries/responses crossing dual-use boundaries
- **Boundary examples**: Ambiguous cases near the permitted/restricted boundary
- **Benign examples**: Clearly safe biology queries for over-refusal calibration
- **Augmented examples**: Translations, jailbreak templates, formality variations

## License

MIT
"""

    # Create temp directory with dataset files
    import tempfile

    with tempfile.TemporaryDirectory() as tmpdir:
        tmpdir = Path(tmpdir)

        # Write dataset card
        with open(tmpdir / "README.md", "w", encoding="utf-8") as f:
            f.write(dataset_card)

        # Copy data files
        for split in ["train", "val", "test"]:
            src = DATA_PROCESSED / f"{split}.jsonl"
            if src.exists():
                shutil.copy2(src, tmpdir / f"{split}.jsonl")

        # Copy constitution
        if CONSTITUTION_FILE.exists():
            shutil.copy2(CONSTITUTION_FILE, tmpdir / "biosafety_constitution.yaml")

        api.create_repo(repo_id=repo_id, repo_type="dataset", exist_ok=True, private=private)
        api.upload_folder(
            folder_path=str(tmpdir),
            repo_id=repo_id,
            repo_type="dataset",
            create_pr=False,
        )

    logger.info("Dataset uploaded to: https://huggingface.co/datasets/%s", repo_id)
    return f"https://huggingface.co/datasets/{repo_id}"


def main():
    parser = argparse.ArgumentParser(description="Export to HuggingFace Hub")
    parser.add_argument(
        "--model", action="store_true",
        help="Export trained model",
    )
    parser.add_argument(
        "--dataset", action="store_true",
        help="Export dataset and constitution",
    )
    parser.add_argument(
        "--repo-prefix", type=str, default="jang1563/bioguard",
        help=(
            "Legacy HuggingFace repo prefix. Used only when --model-repo or "
            "--dataset-repo are omitted."
        ),
    )
    parser.add_argument(
        "--model-repo", type=str, default=None,
        help="Exact HuggingFace model repo ID (default: jang1563/constitutional-bioguard-v4)",
    )
    parser.add_argument(
        "--dataset-repo", type=str, default=None,
        help="Exact HuggingFace dataset repo ID (default: <repo-prefix>-dataset)",
    )
    parser.add_argument(
        "--model-dir", type=str, default=None,
        help="Model directory (default: models/deberta_bioguard_v4_response_diverse/)",
    )
    parser.add_argument(
        "--card-file", type=str, default=None,
        help="Hand-maintained model card to copy into the model directory before upload.",
    )
    parser.add_argument(
        "--private", action="store_true",
        help="Create private repos",
    )
    parser.add_argument(
        "--regenerate-card", action="store_true",
        help="Overwrite an existing model card with the generated template "
             "(default: preserve a hand-maintained card if present)",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO)

    if not args.model and not args.dataset:
        args.model = True
        args.dataset = True

    model_dir = (
        Path(args.model_dir)
        if args.model_dir
        else MODELS_DIR / "deberta_bioguard_v4_response_diverse"
    )
    model_repo = args.model_repo or "jang1563/constitutional-bioguard-v4"
    dataset_repo = args.dataset_repo or f"{args.repo_prefix}-dataset"
    card_file = Path(args.card_file) if args.card_file else None

    if args.model:
        if not model_dir.exists():
            logger.error("Model directory not found: %s", model_dir)
            sys.exit(1)
        export_model(
            model_dir=model_dir,
            repo_id=model_repo,
            private=args.private,
            regenerate_card=args.regenerate_card,
            card_file=card_file,
        )

    if args.dataset:
        export_dataset(
            repo_id=dataset_repo,
            private=args.private,
        )


if __name__ == "__main__":
    main()
